export class Address {
  constructor(
    public Id: number,
    public Address: string,
    public City: string,
    public State: string,
    public Country: string,
    public ZipCode: string
  ) {
    this.Id = Id;
    this.Address = Address;
    this.City = City;
    this.State = State;
    this.Country = Country;
    this.ZipCode = ZipCode;
  }
}
